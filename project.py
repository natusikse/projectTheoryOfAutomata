import itertools

"""
the function generate_L: function, that generates all the sentences that can 
exist in the regular set L (Part 2 in project)
"""

def generate_L(max_y=2, max_z=2):
    # these are the abbreviations used in paper

    X = "the woman such that"
    Y = "the man such that"
    she = "she"
    W = "left is here"

    Z_options = [
        "gave him to him",
        "gave him to this",
        "gave this to him",
        "gave this to this"
    ]

    sentences = []

    for y_count in range(max_y + 1):
        y_part = ' '.join([Y] * y_count)

        for z_count in range(max_z + 1):
            for z_sequence in itertools.product(Z_options, repeat=z_count):
                #generate the sentence as L = X Y* she Z* W
                z_part = ' '.join(z_sequence)
                sentence = ' '.join(filter(None, [X, y_part, she, z_part, W]))
                sentences.append(sentence)

    return sentences

